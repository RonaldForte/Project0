package com.bank.repository;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

import com.bank.model.Customer;
import com.bank.util.ConnectionUtil;

public class CustomerDaoImpl implements CustomerDao{

/* customer: customer_id, username, password, first_name, last_name, address, phone, email */

  @Override
  public Optional<Customer> findByUsername(String username) {
      String sql = "SELECT customer_id, username, password, first_name, last_name, address, phone, email FROM customer WHERE username = ?";

      try (Connection conn = ConnectionUtil.getConnection();
        PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, username);

        try (ResultSet rs = ps.executeQuery()) {
          if (rs.next()) {
            return Optional.of(new Customer(
              rs.getInt("customer_id"),
              rs.getString("username"),
              rs.getString("password"),
              rs.getString("first_name"),
              rs.getString("last_name"),
              rs.getString("address"),
              rs.getString("phone"),
              rs.getString("email")));
          }
        }
      } catch (SQLException e) {
        throw new RuntimeException("Error finding customer " + username, e);
      }
    return Optional.empty();
  }

  @Override
  public Customer create(Customer customer) {
    String sql = "INSERT INTO customer (username, password, first_name, last_name, address, phone, email) VALUES (?, ?, ?, ?, ?, ?, ?)";

    try(Connection conn = ConnectionUtil.getConnection();
      PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) { //RETURN_GENERATED_KEYS give us back the populated customerId
        // ps.setInt(1, customer.getCustomerId()); customer_id is generated by the db
        ps.setString(1, customer.getUsername());
        ps.setString(2, customer.getPassword());
        ps.setString(3, customer.getFirstName());
        ps.setString(4, customer.getLastName());
        ps.setString(5, customer.getAddress());
        ps.setString(6, customer.getPhone());
        ps.setString(7, customer.getEmail());
        
        ps.executeUpdate(); //Insert is executeUpdate not executeQuery!!!

        try(ResultSet keys = ps.getGeneratedKeys()){
          if (keys.next()) {
            customer.setCustomerId(keys.getInt("customer_id"));
          }
        }
        return customer;
    } catch (SQLException e) {
      throw new RuntimeException("Error creating customer", e);
    }
  }




  @Override
  public List<Customer> findAllCustomers() {
    List<Customer> customers = new ArrayList<>();
    String sql = "SELECT customer_id, username, password, first_name, last_name, address, phone, email FROM customer";

    try (Connection conn = ConnectionUtil.getConnection();
      PreparedStatement ps = conn.prepareStatement(sql)) {
      try (ResultSet rs = ps.executeQuery()) {
        while (rs.next()) {
          customers.add(new Customer(
            rs.getInt("customer_id"),
            rs.getString("username"),
            rs.getString("password"),
            rs.getString("first_name"),
            rs.getString("last_name"),
            rs.getString("address"),
            rs.getString("phone"),
            rs.getString("email")));
        }
      }
    } catch (SQLException e) {
      throw new RuntimeException("Error retrieving customers", e);
    }
    return customers;
  }

  @Override
  public Optional<Customer> findById(int customerId) {
    String sql = "SELECT customer_id, username, password, first_name, last_name, address, phone, email FROM customer WHERE customer_id = ?";

    try (Connection conn = ConnectionUtil.getConnection();
      PreparedStatement ps = conn.prepareStatement(sql)) {

      ps.setInt(1, customerId);

      try (ResultSet rs = ps.executeQuery()) {
        if (rs.next()) {
          return Optional.of(new Customer(
            rs.getInt("customer_id"),
            rs.getString("username"),
            rs.getString("password"),
            rs.getString("first_name"),
            rs.getString("last_name"),
            rs.getString("address"),
            rs.getString("phone"),
            rs.getString("email")));
        }
      }
    } catch (SQLException e) {
      throw new RuntimeException("Error finding customer " + customerId, e);
    }
    return Optional.empty();
  }

}